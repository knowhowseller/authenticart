$word = New-Object -ComObject Word.Application
$word.Visible = $false

function NewDoc {
    $d = $word.Documents.Add()
    $d.PageSetup.TopMargin    = $word.CentimetersToPoints(3.0)
    $d.PageSetup.BottomMargin = $word.CentimetersToPoints(3.0)
    $d.PageSetup.LeftMargin   = $word.CentimetersToPoints(3.0)
    $d.PageSetup.RightMargin  = $word.CentimetersToPoints(2.5)
    return $d
}

function H1($d,[string]$t){ $s=$d.Application.Selection; $s.Style=-2; $s.TypeText($t); $s.TypeParagraph() }
function H2($d,[string]$t){ $s=$d.Application.Selection; $s.Style=-3; $s.TypeText($t); $s.TypeParagraph() }
function P($d,[string]$t) { $s=$d.Application.Selection; $s.Style=-1; $s.TypeText($t); $s.TypeParagraph() }
function Br($d)           { $s=$d.Application.Selection; $s.Style=-1; $s.TypeParagraph() }

function AddTbl($d,[string[][]]$data){
    $s=$d.Application.Selection
    $rows=$data.Length; $cols=$data[0].Length
    $rng=$s.Range
    $tbl=$d.Tables.Add($rng,$rows,$cols)
    try { $tbl.Borders.Enable=$true } catch {}
    for($r=0;$r-lt$rows;$r++){
        for($c=0;$c-lt$cols;$c++){
            $cell=$tbl.Cell($r+1,$c+1)
            $cell.Range.Text=$data[$r][$c]
            if($r-eq0){ $cell.Range.Font.Bold=$true }
        }
    }
    $s.MoveRight(12,1); $s.TypeParagraph()
}

function SaveClose($d,[string]$path){
    $d.SaveAs2($path,16); $d.Close($false)
    Write-Host "저장: $path"
}

