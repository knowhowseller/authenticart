$word = New-Object -ComObject Word.Application
$word.Visible = $false
$doc = $word.Documents.Add()
$sel = $word.Selection

$doc.PageSetup.TopMargin    = $word.CentimetersToPoints(3.0)
$doc.PageSetup.BottomMargin = $word.CentimetersToPoints(3.0)
$doc.PageSetup.LeftMargin   = $word.CentimetersToPoints(3.0)
$doc.PageSetup.RightMargin  = $word.CentimetersToPoints(2.5)

function H1([string]$t){ $sel.Style=-2; $sel.TypeText($t); $sel.TypeParagraph() }
function H2([string]$t){ $sel.Style=-3; $sel.TypeText($t); $sel.TypeParagraph() }
function H3([string]$t){ $sel.Style=-4; $sel.TypeText($t); $sel.TypeParagraph() }
function P([string]$t) { $sel.Style=-1; $sel.TypeText($t); $sel.TypeParagraph() }
function Br { $sel.Style=-1; $sel.TypeParagraph() }
function Bold([string]$t){
    $sel.Style=-1
    $sel.Font.Bold=$true; $sel.TypeText($t); $sel.Font.Bold=$false
    $sel.TypeParagraph()
}

function AddTable([string[][]]$data){
    $rows=$data.Length; $cols=$data[0].Length
    $range=$sel.Range
    $tbl=$doc.Tables.Add($range,$rows,$cols)
    $tbl.Style="Table Grid"
    $tbl.Borders.Enable=$true
    for($r=0;$r-lt$rows;$r++){
        for($c=0;$c-lt$cols;$c++){
            $cell=$tbl.Cell($r+1,$c+1)
            $cell.Range.Text=$data[$r][$c]
            if($r-eq0){ $cell.Range.Font.Bold=$true; $cell.Shading.BackgroundPatternColor=-603914241 }
        }
    }
    $sel.MoveRight(12,1)
    $sel.TypeParagraph()
}

