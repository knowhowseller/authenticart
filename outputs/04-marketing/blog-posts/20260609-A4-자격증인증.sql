## 어떤 경우에 민간 자격증 취득이 도움이 되나요?

자격증 취득이 실질적으로 유리한 경우도 있습니다. 아래 상황에 해당한다면 취득을 고려해 볼 만합니다.

- 학교·도서관·복지관 등 공공 기관 출강 시 자격증 제출을 요구하는 경우
- 공예 기법의 기초를 체계적으로 배우고 싶은 경우
- 교육 이력을 공식 서류로 남기고 싶은 경우

반대로 오센틱아트 플랫폼에서 클래스를 열고 수강생을 모집하는 것이 1차 목표라면, 자격증 취득보다 포트폴리오 완성과 첫 클래스 개설에 먼저 집중하는 방향이 현실적입니다.

