## 공예 강사 자격증, 꼭 따야 할까요?

"레진아트 지도사 자격증을 먼저 취득해야 강사로 시작할 수 있는 걸까요?" 공예 강사를 준비하면서 가장 많이 받는 질문 중 하나입니다.

공예 분야에는 레진아트 지도사, 캔들 마스터, 플라워 어레인지먼트 강사 등 다양한 민간 자격증이 있습니다. 교육 과정에 수십만 원에서 수백만 원을 투자하기 전에, 그 자격증이 실제로 무엇을 증명하는지, 플랫폼 인증과는 어떻게 다른지 먼저 파악해 두는 것이 중요합니다.

