## 자격증 없이 강사를 시작하려면 어떻게 준비하나요?

오센틱아트에서는 민간 공예 자격증 없이도 강사 신청이 가능합니다. 포트폴리오와 역량 심사를 거쳐 통과하면 바로 클래스를 개설할 수 있습니다. 심사 전 다음 항목을 준비해 두면 도움이 됩니다.

**포트폴리오 정리**: 완성한 작품 중 5~10점을 선별해 자연광에서 촬영한 사진을 준비하세요. 장르가 여럿이라면 가장 자신 있는 1~2개에 집중하는 것이 심사에 유리합니다.

**커리큘럼 초안 작성**: 입문자를 위한 2시간 원데이클래스 1회 분량으로, 준비물 목록과 진행 순서를 간략하게 구성해 두세요.

**강사 소개 문구**: 이 장르를 시작한 계기, 어떤 수업을 진행하고 싶은지를 짧게 작성해 두면 신청서 작성이 빠릅니다.

민간 자격증을 이미 보유한 분이라면 심사 서류로 함께 제출할 수 있으며, 포트폴리오와 함께 참고 자료로 활용됩니다. 자격증 보유 여부와 무관하게 심사 결과는 포트폴리오와 역량을 기반으로 결정됩니다.

