## 민간 자격증과 플랫폼 인증은 어떻게 다른가요?

오센틱아트의 강사 인증은 **플랫폼 자체 기준에 따라 포트폴리오와 강의 역량을 심사해 부여하는 인증**입니다. 민간 협회가 발급하는 자격증과는 발급 주체, 심사 기준, 목적이 다릅니다.

| 구분 | 민간 자격증 | 오센틱아트 강사 인증 |
|------|------------|------------------|
| 발급·인증 주체 | 민간 협회·사설 교육 기관 | 오센틱아트 플랫폼 |
| 국가공인 여부 | 국가공인 아님 (민간 자격) | 플랫폼 자체 인증 (국가공인 아님) |
| 심사·취득 기준 | 지정 교육 과정 수료 | 포트폴리오·강의 역량 기반 심사 |
| 강사 활동 연결 | 별도 채널·공방 필요 | 인증 즉시 클래스 개설 가능 |
| 주요 활용 범위 | 이력 문서, 특정 기관 제출용 | 오센틱아트 플랫폼 내 강사 활동 |
| 취득 비용 | 교육 과정 수강료 발생 | 심사 통과 시 별도 비용 없음 |

두 인증 모두 국가공인 자격이 아니라는 점에서는 동일합니다. 차이는 **어디서 강사로 활동하느냐**에 따라 어느 쪽이 더 직접적으로 필요한가입니다.

