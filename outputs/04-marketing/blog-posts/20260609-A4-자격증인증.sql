## 민간 자격증의 의미와 한계는 무엇인가요?

민간 자격증은 다음과 같은 의미가 있습니다.

- 특정 교육 과정을 수료했다는 공식 이력 문서
- 공예 기법의 기초 과정을 체계적으로 학습한 증빙
- 수강생에게 강사 신뢰도를 전달하는 보조 수단

반면 실무에서 자주 확인되는 한계도 있습니다.

- 발급 기관이 다르면 상호 인정이 되지 않는 경우가 많습니다.
- 자격증 취득이 곧 강의 역량을 보증하지는 않습니다.
- 취득 비용과 시간이 상당하지만, 클래스 개설과 직접 연결되지 않는 경우가 있습니다.
- 수강생이 강사를 선택할 때 포트폴리오와 후기를 우선으로 보는 경향이 있습니다.

이는 민간 자격증이 불필요하다는 뜻이 아닙니다. **실무 목적에 맞게 취득 여부를 판단하는 것이 중요하다는 의미입니다.**

