## 민간 자격증은 정확히 무엇인가요?

국내 공예 분야의 자격증 대부분은 **민간 자격증**입니다. 국가기술자격법에 따른 국가공인 자격이 아니라, 민간 협회나 사설 기관이 자체 기준으로 발급하는 자격입니다.

민간 자격증은 자격기본법에 따라 민간자격 등록 데이터베이스(민간자격정보서비스)에 등록된 것과 그렇지 않은 것으로 나뉩니다. 등록 여부와 관계없이 **국가공인과는 다른 개념**입니다.

레진아트 지도사 자격증, 캔들 아티스트 자격증, 플라워 강사 자격증 등은 대부분 이 민간 자격 범주에 해당합니다. 발급 기관마다 교육 내용과 수료 기준이 다르며, 타 기관에서는 동등하게 인정되지 않는 경우도 있습니다.

