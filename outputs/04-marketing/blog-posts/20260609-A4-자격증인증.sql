## 실무에서 정말 필요한 것은 무엇인가요?

수강생이 클래스를 예약할 때 실제로 확인하는 것들을 중심으로 살펴보면, 강사를 선택하는 기준은 대체로 다음과 같습니다.

**포트폴리오와 작품 사진**: 수강생이 완성하게 될 결과물을 시각적으로 확인하는 핵심 기준입니다. 완성도 높은 작품 사진 10장이 자격증 1개보다 예약 전환에 더 직접적인 영향을 줍니다.

**커리큘럼의 명확성**: 2시간 안에 무엇을 배울 수 있는지, 준비물이 무엇인지, 어떤 수준의 참여자에게 맞는 수업인지가 명확할수록 예약이 늘어납니다.

**수강 후기와 반복 수강**: 첫 수강생의 긍정적인 후기는 이후 수강생 모집에 가장 강력한 신뢰 근거가 됩니다.

**강사 소개의 진정성**: 어떤 계기로 이 장르를 시작했는지, 수업에서 무엇을 중요하게 생각하는지를 구체적으로 서술한 강사 소개는 수강 결정에 영향을 줍니다.

자격증은 이 중에서 강사 소개의 한 항목으로 포함될 수 있지만, 단독으로 강사 경쟁력을 결정하는 요소가 되기는 어렵습니다.

