## 강사로 안착하기까지 얼마나 걸렸을까요?

모든 전환이 순조롭지는 않습니다. 클래스 취소, 재료비 손실, 예약 없는 주도 있었습니다. A씨는 3개월간 직장을 유지하면서 주말 클래스로 경험을 쌓는 방식을 택했습니다. 공예 부업으로 시작해 운영 감각을 익힌 뒤 전업 전환 시점을 결정하는 경로였습니다.

안착 과정에서 도움이 된 것들을 정리하면 다음과 같습니다.

| 단계 | 핵심 행동 |
|------|---------|
| 클래스 개설 초기 | 수강 요청 수요 확인 후 일정 오픈 |
| 수강생 유입 | SNS 작업 과정 공유 + 강사 프로필 링크 연결 |
| 운영 안정화 | 재료 원가 계산 → 수강료 재조정 |
| 전업 전환 결정 | 3개월 평균 운영 데이터 확인 후 판단 |

기업 팀빌딩이나 단체 클래스 수요가 생기면서 [단체 출강 문의](/group-request) 채널을 활용한 것도 운영 폭을 넓히는 데 도움이 됐습니다.

