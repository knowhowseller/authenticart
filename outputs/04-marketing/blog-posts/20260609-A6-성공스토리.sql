## 공방도 자격증도 없는데 강사 신청이 가능했을까요?

오센틱아트 강사 신청 페이지를 처음 열었을 때 A씨가 가장 놀란 점은 민간 자격증이 필수 항목이 아니라는 것이었습니다. 오센틱아트는 포트폴리오와 역량 기반 심사를 통해 강사 인증을 부여하는 공예 강사 양성 플랫폼입니다. 오센틱아트 인증은 플랫폼 자체 인증으로, 국가공인 자격증과는 구분됩니다.

신청서에는 활동 장르, 작품 사진, 강사 소개를 입력했습니다. A씨는 3년치 완성작 중 완성도가 높은 레진 작품 7점을 골라 스마트폰으로 다시 촬영했습니다. 창가 자연광 아래서 배경지를 깔고 찍으니 생각보다 그럴듯한 포트폴리오가 됐습니다.

공방이 없다는 걱정은 신청 과정에서 자연스럽게 해소됐습니다. 오센틱아트에서는 수강생이 강사 공간으로 방문하는 형태 외에도 강사가 수강생 쪽으로 출강하는 방문 클래스 방식으로 운영할 수 있기 때문입니다. 공방 임대 비용 없이 시작할 수 있다는 점이 결정적이었습니다.

