## 전환을 결심하게 된 계기는 무엇이었을까요?

A씨(30대, 직장인)는 퇴근 후 레진아트 유리컵을 만드는 것이 하루 중 가장 좋아하는 시간이었습니다. 3년 넘게 주말마다 작품을 만들다 보니 자연스럽게 지인들이 "어떻게 하는 거야?"라고 물어오기 시작했고, 거실 한쪽을 재료 박스가 채워 나갔습니다.

