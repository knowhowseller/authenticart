## 심사 결과를 기다리는 동안 무엇을 준비했나요?

심사 결과를 기다리는 동안 A씨는 첫 클래스 커리큘럼 초안을 써봤습니다. "2시간 안에 레진 키링 2개 완성"이라는 목표를 잡고, 재료 목록과 진행 순서를 노트에 정리했습니다. 준비물 원가를 계산해 수강료를 산정해보니, 생각보다 수익 구조를 명확하게 그려볼 수 있었습니다.

오센틱아트의 수익 구조는 단순합니다. PG 수수료 3.3%와 플랫폼 수수료 10%를 합산한 13.3%가 공제되고, **강사는 수강생 결제액의 86.7%를 수령**합니다. 실제 수입은 운영 횟수, 지역, 수강 인원에 따라 달라지며 특정 금액이 보장되지는 않습니다.

심사를 기다리는 그 2주가 오히려 첫 클래스를 가장 단단하게 준비하는 시간이 됐습니다.

