## 첫 클래스, 어떤 현실이 기다리고 있었을까요?

심사를 통과하고 클래스를 개설했지만 처음 며칠은 예약이 없었습니다. 이 부분은 취미를 직업으로 전환하는 과정에서 많은 분들이 경험하는 현실입니다.

A씨가 택한 방법은 두 가지였습니다. 첫째, 인스타그램에 작업 과정 영상과 완성작을 꾸준히 올리며 강사 프로필 링크를 달았습니다. 둘째, 오센틱아트의 수강 요청 시스템에서 해당 지역·장르의 수요를 확인하고 클래스 일정을 조율했습니다. 수강생이 원하는 시간대에 클래스를 맞춰 여는 방식이 초반 예약으로 연결됐습니다.

첫 수강생은 30대 직장인 여성 2명이었습니다. 강습 당일 A씨는 준비한 커리큘럼 순서가 예상보다 30분 일찍 끝날 것 같아 즉흥으로 응용 디자인 시간을 추가했습니다. 첫 클래스치고는 매끄럽지 않았지만, 수강생들은 완성한 키링을 손에 쥐고 "이거 팔아도 되겠다"고 했습니다. 그 한마디가 A씨에게는 첫 확신이었습니다.

