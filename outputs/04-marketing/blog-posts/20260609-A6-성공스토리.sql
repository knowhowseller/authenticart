공예 강사 전업 전환이 모든 분께 같은 결과를 만들어주지는 않습니다. 운영 방식, 지역, 장르, 활동 빈도에 따라 결과는 다릅니다. 다만 시작을 가로막던 "자격증이 없어서", "공방이 없어서"라는 이유는 오센틱아트 강사 신청 앞에서는 더 이상 결정적인 장벽이 아닙니다.

