## 견적 문의 전 준비해야 할 정보는 무엇인가요?

아래 항목을 미리 정리해두면 상담 1회로 정확한 견적을 받을 수 있습니다.

1. **예상 인원 수** — 최소·최대 범위 포함 (예: 25~30명)
2. **희망 장르** — 정해지지 않았다면 행사 성격(팀빌딩·복지·기념 행사 등)을 알려주면 추천 가능
3. **희망 진행 시간** — 행사 전체 일정 중 공예 체험에 배정 가능한 시간
4. **행사 장소** — 회사 사무실·회의실·외부 행사장·지역 명시
5. **희망 날짜** — 특정 일자 또는 가능 기간 범위
6. **예산 범위** — 총액 또는 인당 기준 (선택 사항이나 제공 시 상담 속도 향상)
7. **특이 사항** — 임산부·알레르기 참가자, 기업 로고 삽입, 개인 포장 필요 여부

