## 진행 시간이 길면 비용이 얼마나 달라지나요?

공예 체험 진행 시간은 크게 세 가지 유형으로 구분됩니다. 시간이 길어질수록 강사 운영비와 재료 투입량이 늘어나므로 총 비용에 영향을 줍니다.

| 유형 | 시간 범위 | 특징 |
|------|---------|------|
| 단기 체험 | 1.5~2시간 | 입문·체험 목적, 간단한 작품 완성 |
| 표준 체험 | 2~2.5시간 | 단체 행사 일반적 구성, 완성도 높은 작품 가능 |
| 심화 체험 | 3시간 이상 | 디테일 작업, 팀 협업 프로그램, 소수 정예에 적합 |

시간 선택은 참가자의 집중력 지속 시간, 행사 일정 내 배정 가능한 시간, 원하는 작품 완성도를 기준으로 결정하는 것이 좋습니다.

