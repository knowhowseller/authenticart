## 인원 규모에 따라 비용 구성이 달라지나요?

인원 수는 단체 공예 체험 견적에서 가장 직접적인 영향을 주는 변수입니다. 일반적으로 참여 인원이 늘어날수록 강사 1인이 담당하는 인원 수가 늘어나고, 일정 규모 이상에서는 **보조 강사 투입 여부**가 추가 변수로 작용합니다.

규모별로 달라지는 구성 요소를 정리하면 다음과 같습니다.

- **10~20인:** 강사 1인으로 진행 가능한 기본 구성. 집중도 높은 체험 가능
- **21~40인:** 장르에 따라 보조 강사 배치 검토가 필요한 구간
- **41인 이상:** 장르·진행 시간에 따라 멀티 강사 구성, 팀 분반 운영 방식 검토

규모가 클수록 사전 협의 시간이 길어지고, 장소 조건(테이블 면적, 환기, 콘센트) 확인이 더 중요해집니다.

