## 예산별로 어떻게 구성하면 좋을까요?

공예 체험 비용은 인원·장르·시간의 조합에 따라 범위가 달라집니다. 아래는 **예산 활용 방향에 대한 구성 팁**이며, 확정 단가가 아닌 계획 단계의 참고 기준입니다. 실제 비용은 상담을 통해 확인하세요.

**예산을 효율적으로 활용하려면:**
- 인원이 많을수록 재료비 부담이 커지므로, 재료비 단가가 낮은 장르(캔들·회화 등)를 선택하면 총 비용 관리에 유리합니다.
- 진행 시간을 줄이면 강사 운영비를 절감할 수 있지만, 작품 완성도가 낮아질 수 있습니다.
- 브랜딩 패키징(기업 로고 포함 포장)은 예산 여유가 있을 때 추가하는 옵션입니다.

**체험 퀄리티를 높이려면:**
- 소규모(10~20인)에서 주얼리·도자기 등 재료비 높은 장르를 선택하면 참가자 만족도가 높아질 수 있습니다.
- 보조 강사 배치나 심화 시간 구성으로 완성도와 집중 케어를 높일 수 있습니다.

