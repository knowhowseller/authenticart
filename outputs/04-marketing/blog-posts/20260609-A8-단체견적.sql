## 단체 공예 체험 견적이 왜 이렇게 제각각인가요?

기업·기관 담당자가 단체 공예 체험을 알아볼 때 가장 먼저 부딪히는 벽이 있습니다. "견적을 뽑아보려고 검색했더니 비용이 천차만별이고, 어떤 기준으로 다른 건지 알 수가 없다"는 것입니다.

이유는 간단합니다. 단체 공예 체험 견적은 단일 상품이 아니라 **다섯 가지 변수의 조합**이기 때문입니다. 같은 레진아트 체험이라도 10명과 50명의 비용은 다르고, 2시간과 3시간의 구성도 다르며, 서울 도심 사무실과 지방 행사장의 조건도 다릅니다.

이 글은 단체 공예 체험 견적을 구성하는 변수를 하나씩 풀어내고, 담당자가 문의 전 준비해야 할 정보와 예산별 구성 팁을 정리합니다.

