## 장르별로 비용 구조가 어떻게 다른가요?

공예 체험 비용에서 장르 선택이 중요한 이유는 재료비 구조가 장르마다 다르기 때문입니다. 단체 행사 성격과 예산을 함께 고려해 장르를 선택하는 것이 좋습니다.

| 장르 | 재료비 수준 | 권장 인원 | 진행 시간 | 특징 |
|------|-----------|---------|---------|------|
| 레진아트 (코스터·키링) | 중간 | 10~50인 | 2~2.5시간 | 완성도 높음, 참여 장벽 낮음 |
| 소이캔들 | 중간 | 10~40인 | 1.5~2시간 | 향 체험, 인테리어 선물 활용 |
| 프리저브드플라워 | 중간~높음 | 10~30인 | 2~3시간 | 고급스러운 결과물 |
| 주얼리·자수 | 낮음~중간 | 10~20인 | 2.5~3시간 | 집중형, 소수 정예 적합 |
| 도자기·목공예 | 중간~높음 | 10~20인 | 2.5~3시간 | 협업 체험, 도구 세팅 면적 필요 |
| 회화 (캔버스·수채화) | 낮음~중간 | 10~50인 | 2~3시간 | 장르 진입 장벽 낮음, 대규모 행사에 적합 |

재료비 수준은 선택하는 재료 사양(기본/고급)에 따라 달라질 수 있습니다. 장르가 정해지지 않은 상태라면 문의 시 담당자가 행사 성격에 맞는 장르 추천을 제공합니다.

