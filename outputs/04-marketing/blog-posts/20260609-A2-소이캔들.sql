## 소이캔들 향 조합은 어떻게 하나요?

소이캔들 클래스에서 가장 즐거운 단계 중 하나가 향 선택입니다. 강사가 클래스에 비치한 향료 중 원하는 향을 직접 테스트하고 고릅니다.

### 처음 향을 고를 때 기준은 어떻게 잡으면 되나요?

향료는 크게 다음 계열로 나뉩니다.

- **플로럴**: 로즈, 재스민, 피오니 등 꽃향 계열
- **우디·머스크**: 샌달우드, 시더우드, 화이트 머스크 등 차분한 향
- **프루티**: 자몽, 레몬, 복숭아 등 상큼하고 밝은 향
- **그린·허브**: 라벤더, 유칼립투스, 민트 등 식물성 향
- **베이커리·스위트**: 바닐라, 코코넛, 카라멜 등 달콤한 향

두 계열을 혼합하는 것도 가능합니다. 강사가 조합 비율과 어울리는 계열을 안내해 주므로, 처음이라면 강사 추천 조합을 기준으로 선택하고 조금씩 변형해 보는 방식이 편합니다.

향료 첨가 비율(향률)은 왁스 무게 대비 일반적으로 6~10% 범위에서 결정되며, 이 부분은 강사가 직접 계산해 줍니다.

