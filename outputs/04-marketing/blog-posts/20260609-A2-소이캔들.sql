## 소이캔들 클래스에서 안전 주의사항은 무엇인가요?

소이캔들 작업은 가열 기구와 향료를 다루기 때문에 몇 가지 안전 사항을 미리 알아두는 것이 좋습니다.

### 화기·향료 관련 안전 체크리스트는 어떻게 되나요?

- **가열 기구 주의**: 왁스를 녹일 때 핫플레이트 또는 이중 가열을 사용하는데, 직접 불꽃을 다루는 경우 강사의 안내 외 임의 조작은 피하세요.
- **온도 확인**: 소이왁스는 일반적으로 60~70°C 범위에서 용해합니다. 온도계를 반드시 확인하며, 과열 시 향료 성분이 변질될 수 있습니다.
- **환기 필수**: 향료는 농도가 높을수록 자극이 될 수 있습니다. 공방 클래스는 대부분 환기 시설을 갖추고 있으나, 향에 민감한 분은 마스크를 지참하면 더 편합니다.
- **완성 캔들 이동 시 주의**: 굳은 캔들이라도 완전 경화 전에 충격을 주면 표면에 크랙이 생길 수 있습니다. 이동 시 세워서 운반하세요.
- **첫 사용 시 연소 시간**: 첫 점화 시 왁스 표면 전체가 녹을 때까지 1~2시간 이상 연소하는 것이 권장됩니다. 이 부분은 강사가 클래스 마무리 단계에서 안내해 줍니다.

