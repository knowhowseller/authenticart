## 공방 없이 강사로 활동할 때 현실적인 제약은 무엇인가요?

공방이 없는 운영 방식이 장점만 있는 것은 아닙니다. 미리 알고 대비하면 문제를 줄일 수 있습니다.

**재료 보관과 준비**: 수업마다 재료를 직접 챙겨야 합니다. 자주 사용하는 재료는 정리된 키트 형태로 미리 패킹해 두면 이동이 편해집니다.

**이동 시간과 체력**: 출강이 많아질수록 이동 시간이 누적됩니다. 활동 지역을 미리 설정하고 이동 거리를 고려해 일정을 조율하는 것이 좋습니다.

**장소 섭외의 불확실성**: 대관 공간의 경우 원하는 날짜에 예약이 안 될 수 있습니다. 2~3곳의 대관 장소를 미리 파악해 두면 일정 조율이 수월합니다.

**수강생 신뢰도**: 공방 없이 운영하면 처음에는 강사 신뢰도를 입증하기 어려울 수 있습니다. 오센틱아트 강사 프로필을 충실히 작성하고, 수업 결과물 사진을 꾸준히 업로드하면 신뢰도를 쌓을 수 있습니다.

