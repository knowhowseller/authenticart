**2. 핸드메이드 전문몰**: 핸드메이드·작가 작품에 특화된 플랫폼입니다. 작품의 감도와 가치를 이해하는 구매자가 모이는 채널로, 수공예 작품 노출 환경이 오픈마켓보다 유리합니다.

**3. SNS 채널**: 인스타그램, 핀터레스트, 유튜브 등 비주얼 중심 플랫폼입니다. 팔로워를 통한 브랜딩과 인지도 형성에 강하지만, 플랫폼 자체에 결제 기능이 없어 외부 채널로 연결해야 하는 마찰이 있습니다.

**4. 공예 플랫폼**: 공예 클래스·커뮤니티와 연계된 마켓입니다. 공예에 관심 있는 수강생·강사가 자연스럽게 유입되는 구조로, 작품 구매 의향이 높은 타겟에게 노출됩니다.

