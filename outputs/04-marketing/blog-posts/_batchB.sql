## 공방 창업 비용과 강사 시작 비용을 비교하면 어떻게 되나요?

공방 창업을 먼저 고려하면 비용 계산이 복잡해집니다.

| 항목 | 공방 창업 시 | 출강·방문 강사 시작 시 |
|------|------------|-------------------|
| 보증금 | 수백~수천만 원 (지역·규모에 따라 다름) | 없음 |
| 인테리어·집기 | 수백만 원 이상 | 없음 |
| 월 임대료 | 매월 고정 발생 | 없음 |
| 클래스 등록비 | — | 없음 (오센틱아트 기준) |
| 재료비 | 수강생 인원에 따라 산정 | 수강생 인원에 따라 산정 |
| 수수료 | — | 수강생 결제액의 13.3% |

공방 창업은 거점 공간을 확보한다는 장점이 있지만, 수강생이 채워지지 않아도 임대료는 매달 나갑니다. 출강·방문 강사는 수업이 있을 때만 비용이 발생하는 구조여서 초기 재무 리스크가 낮습니다.

수익이 검증된 뒤 공간을 마련하는 순서가 처음부터 공방 창업에 투자하는 것보다 리스크를 낮추는 방법으로 고려할 수 있습니다. 다만 어떤 방식이 더 유리한지는 개인의 목표·장르·지역·재정 상황에 따라 달라집니다.

