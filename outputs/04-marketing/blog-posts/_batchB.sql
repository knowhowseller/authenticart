## 강사 수익은 어떻게 계산되나요?

오센틱아트 강사 수령액은 고정 기준이 있습니다. PG 수수료(약 3.3%)와 플랫폼 수수료(10%)를 합산한 13.3%가 공제되고, **강사는 수강생 결제액의 86.7%를 수령**합니다.

예시로 수강료 5만 원, 정원 6명 기준 1회 수업 매출은 30만 원이며, 강사 수령액은 약 26만 원입니다. 월 운영 횟수가 늘어날수록 수령액은 비례해 증가하는 구조입니다.

다만 실제 수입은 운영 횟수, 정원 충족률, 장르, 지역에 따라 달라지며, 특정 금액의 수익을 보장하지 않습니다. 수익 계획은 개인 상황에 맞게 직접 산정하는 것이 좋습니다.

[클래스 페이지](/classes)에서 현재 활동 중인 강사들의 수강료 설정 방식을 참고할 수 있습니다.

