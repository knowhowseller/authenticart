## 단체 출강 클래스는 어떻게 연결되나요?

기업 팀빌딩, 학교 방과후 수업, 복지관·요양원 공예 프로그램 등 단체 수요는 강사 개인이 직접 기관에 접근하기 어렵습니다.

오센틱아트는 B2B 출강 수요를 플랫폼에서 수집한 뒤 적합한 강사에게 연결합니다. 기업·학교·복지관이 [단체 출강 문의](/group-request)를 통해 인원, 장르, 희망 일정을 입력하면 오센틱아트 인증 강사 중 매칭이 이루어집니다.

단체 출강은 회당 수강 인원이 많아 매출이 크지만, 재료 준비량이 늘어나는 만큼 준비 시간도 고려해야 합니다. 단체 클래스 경험이 쌓이면 포트폴리오로 활용할 수 있고, 재방문 요청으로 이어지는 경우도 있습니다.

