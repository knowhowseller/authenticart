## **아이디\*** 같은 핸드메이드 전문몰과 오센틱아트 마켓은 어떻게 다른가요?

**아이디\*** 같은 핸드메이드 전문몰은 수공예 작품 구매자층이 넓고 플랫폼 내 작가 커뮤니티가 활성화되어 있다는 강점이 있습니다. 이미 수많은 작가와 구매자가 형성된 시장에 진입하는 방식입니다.

오센틱아트 마켓은 접근 구조가 다릅니다. 오센틱아트는 공예 클래스를 중심으로 운영되는 플랫폼으로, 마켓을 찾는 고객 대부분이 수강생이거나 공예에 관심을 갖고 클래스를 탐색하는 사람들입니다. 즉, **공예 작품 구매 의향이 이미 있는 고객이 자연스럽게 마켓으로 유입**됩니다.

이 구조는 두 가지 이점으로 연결됩니다.

- **작품 판매**: 클래스를 수강하고 장르에 관심이 생긴 수강생이 강사 또는 작가의 작품을 구매하는 경로가 자연스럽게 형성됩니다.
- **재료 벤더**: 클래스에서 특정 재료를 사용한 수강생이 동일 재료를 직접 구매하려는 수요가 마켓으로 연결됩니다.

두 채널 중 하나를 선택해야 하는 것은 아닙니다. 일반 소비자 대상 노출이 목표라면 **아이디\*** 또는 오픈마켓을, 공예 관심 고객을 대상으로 한 전환이 목표라면 오센틱아트 마켓을, 또는 두 채널을 병행하는 방식도 가능합니다.

