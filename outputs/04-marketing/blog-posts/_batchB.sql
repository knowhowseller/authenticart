## 공방 없이 강사가 활동할 수 있는 운영 형태는 무엇이 있나요?

### 출강 클래스 — 강사가 현장으로 찾아가는 방식

기업 사무실, 학교 교실, 복지관 강당 등 수강생이 있는 공간으로 강사가 직접 이동해 수업을 진행합니다. 재료와 도구를 직접 챙겨가야 하는 준비가 필요하지만, 단체 수강생을 한 번에 확보할 수 있어 회당 매출이 높은 편입니다.

오센틱아트는 기업 팀빌딩, 방과후 공예 수업, 복지관·노인정 공예 프로그램 등 B2B 출강 수요를 연결하는 [단체 출강 채널](/group-request)을 운영합니다. 단체 수업 경험이 없는 신규 강사도 플랫폼을 통해 기관과 연결될 수 있습니다.

### 방문 클래스 — 수강생 자택 또는 소규모 공간

수강생 2~4명이 자택이나 소규모 공간을 제공하고, 강사가 그곳으로 방문해 수업을 진행합니다. 이동이 있지만 장소 비용이 들지 않고, 수강생 입장에서도 편안한 환경에서 배울 수 있어 선호도가 있는 형태입니다.

### 단기 대관 클래스 — 스터디룸·카페·문화센터 활용

스터디룸, 카페 대관석, 지역 문화센터 등을 수업 시간만큼 단기 대관해 사용하는 방식입니다. 고정 임대 계약 없이 필요할 때만 공간을 빌리기 때문에 공간 비용이 가변적입니다. 수강료에 대관 비용을 반영해 설정하면 됩니다.

### 수강생 방문 클래스 — 자택 일부 공간 활용

강사가 자택의 거실, 작업실 등 일부 공간을 수업 공간으로 활용하는 방식입니다. 별도 임대 비용이 없고, 자신만의 작업 환경에서 수업을 진행할 수 있습니다. 수강 인원을 소규모로 제한하면 현실적으로 운영 가능합니다.

| 운영 형태 | 장소 준비 | 이동 | 수강 인원 | 초기 비용 |
|----------|---------|------|---------|---------|
| 출강 클래스 | 수강생 측 제공 | 강사 이동 | 10인 이상 가능 | 재료비만 |
| 방문 클래스 | 수강생 자택 등 | 강사 이동 | 2~5인 | 재료비만 |
| 단기 대관 | 강사가 예약 | 강사 이동 | 2~8인 | 대관비 + 재료비 |
| 자택 수강 | 강사 자택 | 수강생 이동 | 1~6인 | 재료비만 |

