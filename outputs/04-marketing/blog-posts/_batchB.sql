## 소매 구매와 도매 구매는 어떻게 다른가요?

공예 재료를 구매하는 방법은 크게 두 가지입니다.

**소매 구매**는 인터넷 쇼핑몰이나 오프라인 공방 재료 상점에서 필요한 만큼 낱개로 사는 방식입니다. 소량 구매가 가능하고 빠르게 받아볼 수 있지만, 단가가 높습니다. 처음 취미로 공예를 시작하거나 한 번 써볼 재료를 살 때는 소매가 편리합니다.

**도매 구매**는 일정 수량 이상을 묶어서 구매하는 방식입니다. 단가가 낮아 재료비 절감이 가능하지만, 최소 주문 수량(MOQ)이 정해져 있는 경우가 많고, 초기 재고를 한꺼번에 사야 한다는 점에서 관리가 필요합니다.

| 구분 | 소매 구매 | 도매 구매 |
|------|----------|----------|
| 구매 단위 | 낱개·소량 | 묶음·대량 |
| 단가 | 높은 편 | 낮은 편 |
| 최소 수량 | 없거나 낮음 | 있는 경우 많음 |
| 적합 상황 | 취미·일회성 구매 | 정기 클래스 운영·작가 활동 |
| 재고 관리 | 필요 없음 | 보관·유통기한 관리 필요 |

정기적으로 클래스를 운영하는 강사나 작품을 꾸준히 제작하는 작가라면, 도매 구매로 전환하는 시점을 고려해 볼 만합니다.

