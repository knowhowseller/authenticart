## 오센틱아트에서 공방 없이 강사를 시작하는 절차는 어떻게 되나요?

공방 없이 오센틱아트 강사로 시작하는 절차는 세 단계입니다.

**1단계 — 강사 신청서 작성**: [/signup/instructor](/signup/instructor)에서 신청서를 작성합니다. 장르 선택, 작품 포트폴리오 업로드, 활동 희망 지역 설정, 운영 형태(출강·방문 등) 선택을 입력합니다. 공방 주소가 없어도 신청이 가능합니다.

**2단계 — 포트폴리오·역량 심사**: 제출한 포트폴리오와 수업 가능성을 기준으로 심사가 진행됩니다. 국가자격증이나 민간 협회 자격증은 필수가 아니며, 작품 완성도와 강의 역량이 중심 평가 기준입니다.

**3단계 — 클래스 개설 및 수강생 모집**: 심사 통과 후 즉시 클래스를 개설할 수 있습니다. 출강·방문·대관 등 원하는 운영 형태로 클래스를 구성하면 됩니다. 단체 클래스가 필요한 기관은 [단체 출강 채널](/group-request)을 통해 연결됩니다.

