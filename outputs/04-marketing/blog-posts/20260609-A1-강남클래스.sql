- **정원 규모 확인**: 4인 이상이라면 해당 클래스의 최대 정원을 미리 확인하고, 인원에 맞는 클래스를 선택합니다.
- **작업 난이도**: 공예 경험이 없는 참여자가 많을수록 완성 시간이 짧고 결과물이 명확한 장르(레진아트·캔들)가 부담 없이 즐기기 좋습니다.
- **장소 이동 동선**: 강남역·역삼역·선릉역 인근 클래스는 식사 전후 동선과 연계하기 편합니다.

