## 집에 분위기를 만들고 싶다면 어떤 장르가 어울리나요?

### 소이캔들과 프리저브드플라워 — 감각형 취미의 특징

만드는 것 자체보다 "완성된 공간"을 원하는 분께는 캔들과 플라워 계열이 잘 맞습니다.

**소이캔들**은 천연 소이 왁스를 녹여 향을 조합하고 용기에 부어 굳히는 장르입니다. 불을 사용하는 작업이지만 과정이 단순해 처음 공예를 접하는 분도 1.5~2시간 내에 완성품을 가져갈 수 있습니다. 향 조합에 취향을 담을 수 있어 선물용으로도 인기 있고, 완성 후 생활 공간에서 실제로 쓸 수 있다는 점이 만족감을 높입니다. 재료를 온라인에서 구입해 집에서 이어가기도 어렵지 않습니다.

**프리저브드플라워·드라이플라워**는 특수 처리한 꽃을 활용해 화병 장식, 리스, 액자 등을 만드는 장르입니다. 생화를 다루는 플로리스트와 달리 원데이클래스에서는 이미 처리된 꽃을 배치하고 구성하는 데 집중하므로, 식물 지식 없이도 참여 가능합니다. 완성된 작품이 인테리어 소품이 되기 때문에, 공간 꾸미기에 관심 있는 분께 만족도가 높습니다.

