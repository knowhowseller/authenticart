## 처음 가는 레진아트 클래스, 준비물이 있나요?

### 강사가 제공하는 재료 목록과 개인 준비 체크리스트는 어떻게 되나요?

결론부터 말하면, **대부분의 레진아트 원데이클래스는 별도 준비물이 없습니다.** 강사가 필요한 재료와 도구를 모두 준비해 옵니다.

**강사 제공 항목 (일반적 기준)**

- UV 레진 또는 에폭시 레진
- 실리콘 몰드 (코스터·키링·트레이 등 작품별 형태)
- 안료·글리터·데코 부품
- 알코올 램프 또는 UV 램프
- 이쑤시개·조색 스틱·혼합 컵
- 장갑·앞치마 (클래스에 따라 제공 여부 다름)

**개인 준비 사항**

- 편한 복장 (레진이 옷에 묻을 수 있으므로 신경 쓰이는 옷은 피하기)
- 필요 시 마스크 (레진 특유의 냄새가 날 수 있음)
- 완성 작품을 담아갈 작은 가방 (굳은 작품은 들고 이동 가능)

레진 작업 시 **환기**가 중요합니다. 대부분의 공방 클래스는 환기 설비를 갖추고 있으나, 클래스 신청 전 공간 환경을 확인해 두면 더 편하게 참여할 수 있습니다.

