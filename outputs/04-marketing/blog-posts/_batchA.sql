레진아트 강사 수입을 솔직하게 이야기하려면 세 가지 변수를 먼저 봐야 합니다. **클래스 1회당 가격**, **정원(수강 인원)**, **월 운영 횟수**입니다. 이 세 숫자의 곱이 월 매출이 되고, 여기서 플랫폼 수수료를 빼면 실수령이 나옵니다.

