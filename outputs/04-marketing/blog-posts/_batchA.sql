## 공예 취미를 취미로만 즐기지 않고 수익으로 연결할 수 있나요?

### 인기 장르에서 강사로 전환하는 경로

오센틱아트의 슬로건은 "취미를 직업으로"입니다. 공예 취미를 즐기다가 클래스를 직접 열고 싶어지는 분들을 위한 경로가 있습니다.

레진아트, 소이캔들, 프리저브드플라워, 자수 등 원데이클래스로 인기 높은 장르는 강사로 전환하는 분들이 많습니다. 오센틱아트는 국가공인 자격증 없이 포트폴리오와 강의 역량 심사를 통해 강사 인증을 받을 수 있으며, 심사 통과 후 즉시 클래스를 개설할 수 있습니다.

공예 취미를 먼저 경험하고 싶다면 [클래스 탐색](/classes)부터 시작하세요. 장르를 충분히 익힌 뒤 강사 전환을 고려하게 된다면 강사 신청 경로도 열려 있습니다.

