## 부업 강사와 전업 강사의 수입 차이가 어느 정도인가요?

강사 활동을 부업으로 시작하는 경우와 전업으로 운영하는 경우의 가장 큰 차이는 **월 운영 횟수**입니다. 주중에 본업이 있는 부업 강사는 주말 위주 월 4~8회 운영이 현실적인 범위이고, 전업 강사는 주중·주말 포함 월 12~20회 이상을 목표로 운영하는 경우가 있습니다.

아래는 두 운영 방식의 예시 비교입니다. 클래스 단가 5만 원, 정원 6명 기준입니다.

| 구분 | 월 운영 횟수 | 월 매출 (정원 충족 시) | 오센틱아트 실수령 |
|------|-----------|-------------------|---------------|
| 부업 (주말 집중) | 4회 | 120만 원 | 약 104만 원 |
| 부업 (주 2회) | 8회 | 240만 원 | 약 208만 원 |
| 전업 (주 2~3회) | 12회 | 360만 원 | 약 312만 원 |
| 전업 (주 3~4회) | 16회 | 480만 원 | 약 416만 원 |

**중요한 변수:** 정원이 항상 채워지는 것은 아닙니다. 수강생 확보에 시간이 걸리는 초기에는 실 수강 인원이 2~3명인 클래스도 많습니다. 또한 재료비, 장소 임차비(공방이 없는 경우 외부 공간 이용료) 등 직접 비용을 차감하면 실질 수익은 위 수치보다 낮아집니다.

이 계산은 예시이며, 개인 운영 상황에 따라 결과가 다릅니다.

