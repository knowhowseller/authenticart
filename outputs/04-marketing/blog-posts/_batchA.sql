플랫폼 매칭 서비스는 강사가 이미 심사를 통과한 상태이므로 기본 자격 검증 단계가 단축됩니다. 오센틱아트는 레진아트·소이캔들·플라워·가죽공예 등 전 장르 공예 강사의 인증·양성 플랫폼으로, 서울·인천·강릉·충주·부산·제주 등 전국 지역 강사 매칭이 가능합니다.

| 항목 | 개인 직접 섭외 | 플랫폼 매칭 |
|------|:---:|:---:|
| 강사 자격 사전 검증 | 담당자 직접 확인 | 플랫폼 심사 통과 강사 |
| 포트폴리오 열람 | 요청 후 개별 수합 | 프로필 페이지 바로 확인 |
