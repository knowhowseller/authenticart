## 레진아트 클래스, 혼자 가도 괜찮나요?

레진아트 원데이클래스는 **혼자 참여하기에 좋은 구조**입니다. 커플이나 친구와 함께 오는 경우도 많지만, 소규모 클래스 특성상 처음 만난 사람들과도 자연스럽게 어울리며 작업하는 분위기입니다.

### 소규모 클래스 구조와 혼자 참여 경험은 어떤가요?

공예 원데이클래스는 대부분 2~8명 내외 소수 정원으로 운영됩니다. 강사가 개별 진행 상황을 직접 봐줄 수 있어, 어느 단계에서 막혀도 바로 도움을 받을 수 있습니다. 대형 강의처럼 뒤쳐질 걱정 없이 내 속도로 진행하는 것이 공예 원데이클래스의 특징입니다.

처음 시작이 어색하더라도 작업을 시작하면 자연스럽게 몰입하게 됩니다. 완성 작품을 손에 쥐었을 때의 만족감이 다음 클래스로 이어지는 경우가 많습니다.

