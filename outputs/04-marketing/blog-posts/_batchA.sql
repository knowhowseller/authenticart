## 레진아트 강사 수익에 영향을 주는 변수는 무엇인가요?

같은 횟수를 운영해도 수익 차이가 생기는 이유가 있습니다. 현실적으로 수익에 영향을 주는 변수들입니다.

**지역**: 인구 밀도가 높고 공예 클래스 수요가 많은 서울·수도권·광역시에서 수강생 확보가 상대적으로 수월한 경향이 있습니다. 소도시는 경쟁이 적지만 수요 풀 자체가 작을 수 있습니다.

**장르**: 레진아트는 키링·코스터 등 결과물이 빠르게 나오고 인스타그램 노출이 용이해 원데이클래스 수요가 안정적인 편입니다. 단, 인기 장르는 강사 공급도 많습니다.

**수강생 재방문·추천**: 초기 수강생이 지인을 데려오거나 재수강하면 모집 비용이 줄어 수익 구조가 좋아집니다. 첫 수강생 확보와 후기 관리가 중요한 이유입니다.

**재료비 관리**: 도매 루트를 확보하거나 재료 구성을 최적화하면 같은 단가에서 수익률이 올라갑니다. 오센틱아트 [재료 쇼핑 페이지](/shop)에서 공예 재료를 확인할 수 있습니다.

**클래스 시간 설계**: 2시간 완성형 클래스는 회전이 빠르고 수강생 만족도가 높습니다. 3~4시간 심화 과정은 단가를 높이는 대신 운영 횟수가 줄어듭니다.

