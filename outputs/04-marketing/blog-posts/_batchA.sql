## 기업 팀빌딩으로 공예 체험이 왜 좋은가요?

회식을 기획할 때마다 드는 고민이 있습니다. "누군가는 술을 못 마시고, 누군가는 노래방이 불편하고, 결국 다들 억지로 참여하는 자리가 된다." 이 문제를 해결하기 위해 팀빌딩 공예 체험을 선택하는 기업이 늘고 있습니다.

공예 체험이 팀빌딩 프로그램으로 선택되는 배경에는 몇 가지 구체적인 이유가 있습니다.

첫째, **참여 장벽이 낮습니다.** 공예 경험이 없어도, 운동을 못해도, 술을 못 마셔도 누구나 작품을 완성할 수 있습니다. 직원 개개인의 체력·기호·주량과 무관하게 전원이 동등하게 참여할 수 있는 구조입니다.

둘째, **함께 만드는 과정이 자연스러운 대화를 만듭니다.** 레진 배합 비율을 묻고, 옆 동료의 작품을 구경하고, 실패해도 웃을 수 있는 분위기가 형성됩니다. 강제된 레크리에이션 없이도 팀원 사이에 공통 경험이 생기는 것이 팀 결속력 향상에 도움이 될 수 있습니다.

셋째, **결과물이 남습니다.** 볼링 점수나 회식 사진은 기억에서 빠르게 사라지지만, 직접 만든 레진 코스터나 캔들은 책상 위에 계속 남아 행사를 떠올리게 합니다.

