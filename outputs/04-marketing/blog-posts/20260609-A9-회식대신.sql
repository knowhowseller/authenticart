## 직장인들은 왜 기존 회식에서 멀어지고 있을까요?

"이번 분기 회식 어떻게 할지 벌써 눈치 보인다"는 말이 HR 담당자 사이에서 흔해졌습니다.

회식 피로감은 새로운 현상이 아닙니다. 그런데 최근 몇 년 사이 분위기가 달라진 것은 직원들이 대안을 직접 요구하기 시작했다는 점입니다. 음주를 선호하지 않는 직원, 야식이 부담스러운 직원, 노래방이 어색한 직원이 숨지 않고 의견을 냅니다. 기업 문화가 바뀐 것이 아니라 직원이 바뀐 것입니다.

이 흐름을 수치로 단정하기는 어렵지만, 기업 복지 플랫폼이나 HR 커뮤니티에서 "회식 대신 팀빌딩"을 묻는 빈도는 분명히 늘었습니다. 참여형 사내 문화 활동 공예 프로그램에 대한 문의가 증가하는 것도 같은 맥락에서 읽힙니다.

