## 공예 팀빌딩이 기존 팀 활동과 다른 점은 무엇인가요?

볼링, 방탈출, 보드게임 같은 활동과 비교했을 때 공예 팀빌딩이 갖는 실질적인 차이가 있습니다.

| 구분 | 볼링·스포츠 | 방탈출·게임 | 공예 팀빌딩 |
|------|-----------|-----------|-----------|
| 신체 조건 영향 | 큼 | 낮음 | 거의 없음 |
| 결과물 | 없음 | 없음 | 작품 1인 1개 |
| 음주 문화 연결 | 높음 | 낮음 | 없음 |
| 담당자 준비 부담 | 중간 | 낮음 | 낮음 (강사 진행) |
| 연령·직급 장벽 | 있음 | 중간 | 낮음 |

특히 연령대가 넓거나 신입과 시니어가 섞인 팀에서 공예 체험은 서로 비슷한 조건으로 시작한다는 점이 장점으로 작용합니다. 공예 경험이 없어도 강사가 처음부터 안내하기 때문에 "나만 못 하는 상황"이 생기지 않습니다.

