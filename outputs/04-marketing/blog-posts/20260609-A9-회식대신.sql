## 사내 문화 활동 공예로 어떤 장르가 적합한가요?

처음 도입하는 기업이라면 진입 장벽이 낮고 완성도 있는 결과물이 나오는 장르부터 시작하는 편이 좋습니다. 오센틱아트는 레진아트, 소이캔들, 프리저브드플라워, 도자기, 주얼리, 자수, 회화, 목공예 전 장르의 인증 강사를 연결합니다.

**첫 도입에 무난한 장르**
- **레진아트 코스터·키링**: 2~2.5시간, 난이도 낮음, 완성도 높음. 결과물을 바로 가져갈 수 있어 만족도가 높은 편입니다.
- **소이캔들**: 1.5~2시간, 향 선택 과정에서 자연스러운 대화 유발. 인테리어·선물 활용이 가능합니다.

**특색 있는 행사를 원할 때**
- **프리저브드플라워**: 2~3시간, 고급스러운 결과물. 시즌 감성 행사에 어울립니다.
- **목공예·회화**: 팀 공동 작품 제작이 가능해 협업 체험으로 설계할 수 있습니다.

어떤 장르를 고를지 확신이 없다면, [단체 출강 문의](/group-request)에서 행사 성격과 인원을 알려주시면 담당자가 장르 추천을 도와드립니다.

