## MZ세대가 선호하는 팀빌딩은 어떤 특징이 있나요?

MZ세대 팀빌딩의 핵심은 세 가지로 요약됩니다.

**선택권 있는 참여.** 강제로 웃어야 하는 레크리에이션 대신, 스스로 뭔가를 만드는 경험을 선호합니다. 잘하거나 못하거나 관계없이 자기 속도로 참여할 수 있는 구조가 중요합니다.

**기억에 남는 결과물.** 그날 밤으로 끝나는 경험보다 책상 위에 남는 물건을 원합니다. 직접 만든 레진 코스터나 향초가 사무실 한 켠에 놓여 있으면 그 자체로 팀의 공통 경험이 됩니다.

**음주 없이도 어색하지 않은 분위기.** 알코올 없이도 대화가 되는 자리. 공예 작업은 손을 바쁘게 만들기 때문에 침묵이 어색하지 않고, 자연스럽게 옆 사람 작품에 시선이 가면서 대화가 시작됩니다.

공예 팀빌딩은 이 세 가지 조건을 고르게 충족하는 몇 안 되는 프로그램 유형 중 하나입니다.

