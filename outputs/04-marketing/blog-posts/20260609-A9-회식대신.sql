## 회식 대신 공예 팀빌딩을 도입하면 어떤 효과를 기대할 수 있나요?

효과를 과장하지 않는 것이 중요합니다. 공예 체험 한 번으로 팀 결속이 극적으로 바뀌지는 않습니다. 그러나 다음과 같은 변화에 도움이 될 수 있습니다.

**대화 접점이 생깁니다.** 같은 테이블에서 2시간을 보내면 업무 외 공통 화제가 생깁니다. 신입사원 환영 행사나 타 부서 합동 행사처럼 서로 잘 모르는 상황에서 특히 유용합니다.

**행사 기억이 오래 남습니다.** 본인이 만든 작품이 사무실에 남아 있는 한, 그 팀빌딩은 기억에 살아 있습니다.

**음주·비음주 구분 없이 전원 참여가 가능합니다.** HR 담당자 입장에서 "아무도 소외되지 않는 행사"를 기획할 수 있다는 것은 실질적인 이점입니다.

**담당자 준비 부담이 낮습니다.** 강사가 프로그램 진행 전반을 맡기 때문에 담당자는 장소와 인원을 확정하는 것 외에 별도 진행 준비가 거의 필요 없습니다.

