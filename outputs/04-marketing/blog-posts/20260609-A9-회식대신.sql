## 공예 팀빌딩은 어떻게 도입하나요?

기획부터 현장 진행까지 흐름을 간단히 정리합니다.

**1단계 — 기획 확정:** 인원 규모, 행사 일정, 장소(사무실·회의실·외부 행사장), 예산 범위를 먼저 정합니다.

**2단계 — 출강 문의 접수:** [오센틱아트 단체 출강 문의 페이지(/group-request)](/group-request)에 인원·희망 장르·일정을 입력하면 담당자가 1~2 영업일 내 연락합니다.

**3단계 — 장르·견적 확정:** 행사 성격과 예산에 맞게 장르를 정하고 견적을 확정합니다.

**4단계 — 강사 매칭 및 현장 진행:** 오센틱아트 인증 강사가 재료와 도구를 가지고 지정 장소로 방문합니다. 서울·인천·부산·제주 등 전국 커버가 가능합니다.

담당자가 별도 진행자 역할을 하지 않아도 강사가 처음부터 끝까지 프로그램을 이끌어갑니다.

