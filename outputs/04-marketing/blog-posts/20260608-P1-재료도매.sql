## 공예 강사와 작가가 재료비를 아껴야 하는 이유가 뭔가요?

공예 클래스를 운영하면서 수익을 계산할 때 수강료만 보는 경우가 많습니다. 그런데 실제로 손에 남는 금액을 결정하는 또 하나의 핵심 변수가 있습니다. 바로 재료비입니다.

수강료에서 플랫폼 수수료를 제외한 다음, 재료비를 빼고 나서야 진짜 수익이 드러납니다. 레진아트 클래스를 예로 들면 1회당 레진·몰드·안료·경화제 등 재료를 소매가로 구매할 경우, 1인당 재료비가 수천 원에서 1만 원 이상이 되기도 합니다. 6명 정원 클래스라면 재료비만 6~8만 원 이상이 나올 수 있고, 이는 수강료 수입의 상당 부분을 차지하게 됩니다.

재료비를 소매가로 계속 부담하는 강사와, 도매가로 구매해 단가를 낮춘 강사 사이에는 같은 수업을 같은 가격에 운영해도 월 수익에 차이가 생길 수 있습니다. 운영 횟수가 많아질수록 이 차이는 누적됩니다.

