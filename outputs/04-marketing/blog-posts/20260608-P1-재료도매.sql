## 오센틱아트 재료 도매 채널은 어떻게 활용하나요?

오센틱아트(www.authenticart.co.kr)는 "취미를 직업으로"라는 슬로건 아래 강사·작가가 클래스 운영에 필요한 재료를 구매할 수 있는 공예 특화 쇼핑 채널을 운영합니다.

**강사 도매가 구매 — [/shop](/shop)**
오센틱아트 강사 회원은 [/shop](/shop)에서 일반 소매가보다 낮은 강사 도매가로 재료를 구매할 수 있습니다. 소매가 대비 절감폭은 품목과 수량에 따라 달라집니다. 레진아트·캔들·플라워 등 주요 공예 장르별 재료를 한 채널에서 구매할 수 있어, 여러 구매처를 돌아다닐 필요가 없습니다.

도매가 구매는 강사 신청 후 인증 심사를 통과한 오센틱아트 강사 회원에게 적용됩니다. 강사가 아니라면 먼저 [강사 신청](/signup/instructor)을 진행한 뒤 이용할 수 있습니다.

**스토어 탐색 — [/shop/stores](/shop/stores)**
[/shop/stores](/shop/stores)에서는 오센틱아트에 입점한 공예 재료 벤더들의 스토어를 확인할 수 있습니다. 벤더별 취급 품목, 전문 장르, 강사 추천 재료 정보를 보고 구매처를 비교할 수 있습니다.

