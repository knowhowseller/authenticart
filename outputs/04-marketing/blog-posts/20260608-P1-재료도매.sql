## 재료비가 강사 수익에 얼마나 영향을 미치나요?

오센틱아트에서 강사는 매출의 86.7%를 수령합니다(PG 3.3%+플랫폼 10% = 13.3% 공제). 월 매출 300만 원 기준 실수령은 약 260만 원 수준입니다.

여기서 재료비가 어떻게 작용하는지 간단히 살펴보면 다음과 같습니다.

| 항목 | 소매 재료비 기준 | 도매 재료비 기준 |
|------|--------------|--------------|
| 월 매출 | 300만 원 | 300만 원 |
| 플랫폼 수수료 (13.3%) | 39.9만 원 | 39.9만 원 |
| 재료비 (예시, 소매 vs 도매) | 50만 원 | 35만 원 |
| **실질 수익** | **약 210만 원** | **약 225만 원** |

위는 예시 수치이며, 실제 재료비는 장르·수업 횟수·구매처에 따라 달라집니다. 하지만 재료비를 줄이는 것만으로도 강사 손에 남는 금액이 달라질 수 있다는 구조는 동일합니다. 개인 운영 상황에 따라 결과는 차이가 있을 수 있습니다.

