## 공방 없이 공예 강사를 할 수 있나요?

공예를 제법 잘 한다는 이야기를 자주 듣지만 막상 강사를 시작하려면 벽이 느껴집니다. "공방부터 차려야 하는 거 아닐까?" 하는 생각이 발목을 잡습니다.

공방은 공예 강사의 필수 조건이 아닙니다. 수강생이 강사의 공간으로 오는 방식 외에도, 강사가 수강생의 공간으로 찾아가는 출강 클래스, 수강생 자택에서 소규모로 진행하는 방문 클래스, 스터디룸이나 카페를 단기 대관해 운영하는 방식이 모두 가능합니다.

오센틱아트(authenticart.kr)는 공예 강사 양성 플랫폼으로, 강사가 공방 없이도 출강·방문·단체 출강 형태로 클래스를 개설하고 수강생을 모집할 수 있는 구조를 갖추고 있습니다. 클래스 등록에 별도 고정비가 없으며, 수강생 결제가 발생했을 때만 수수료(PG 포함 13.3%)가 공제되고 강사는 86.7%를 수령합니다.

공방을 먼저 차려야 한다는 생각 때문에 강사 시작을 미루고 있다면, 이 글이 실질적인 첫걸음이 될 것입니다.

