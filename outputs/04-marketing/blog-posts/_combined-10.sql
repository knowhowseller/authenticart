## 재료를 판매하고 싶은 벤더라면 어떤 채널이 맞나요?

공예 재료를 도매 또는 소매로 판매하는 벤더라면, 실제로 재료를 사용하는 강사와 수강생에게 직접 노출되는 채널이 적합합니다.

오센틱아트는 재료 벤더 입점을 별도로 운영합니다. 클래스 강사들이 재료를 직접 탐색하고, 수강생이 클래스 후 재료 구매로 이어지는 동선이 플랫폼 내에 형성되어 있습니다. 공예 재료의 경우 구매 결정 요인이 '가격'만이 아니라 '강사 추천'과 '품질 신뢰'이기 때문에, 공예 강사와 접점이 많은 채널에서 전환이 더 자연스럽게 일어날 수 있습니다.

입점 가능 재료 카테고리와 조건은 입점 신청 과정에서 확인할 수 있습니다.

