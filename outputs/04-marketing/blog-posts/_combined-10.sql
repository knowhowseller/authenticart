## 행사 준비 담당자가 반드시 체크해야 할 사항은 무엇인가요?

단체 출강 공예 체험을 처음 기획하는 담당자라면 아래 항목을 사전에 확인해두세요. 이 정보를 미리 파악해두면 강사와의 사전 협의가 빠르게 진행됩니다.

**장소 확인 사항**
- 테이블 면적: 참가자 1인당 최소 60cm 이상의 작업 공간이 필요합니다.
- 환기: 레진아트·캔들 장르는 냄새가 발생할 수 있어 환기 가능 여부 확인이 필요합니다.
- 콘센트: 히팅 장비나 UV 램프를 사용하는 장르는 콘센트 위치 확인이 필요합니다.
- 바닥·테이블 보호: 재료가 묻을 수 있어 비닐 시트 또는 방수 테이블 커버 준비를 권장합니다.

**인원 및 일정 확인 사항**
- 참가 인원 확정치(최대 변동 범위 포함)
- 행사 시작·종료 시간 및 강사 준비 시간(행사 시작 30분~1시간 전 도착 가능 여부)
- 임산부·알레르기 참가자 여부 (장르 선택에 영향을 줄 수 있습니다)

**결과물 처리 확인 사항**
- 레진 작품은 경화 시간이 필요합니다. 당일 건조가 완전히 되지 않는 장르의 경우 포장·운반 방법을 사전에 논의합니다.
- 개인 포장 박스나 쇼핑백이 필요한 경우 추가 요청 가능 여부를 확인하세요.

