## 기업 단체 공예 체험은 어떤 장르가 적합한가요?

오센틱아트는 레진아트·소이캔들·플라워·도자기·주얼리·자수·회화·목공예 전 장르의 인증 강사를 연결합니다. 기업 팀빌딩 상황에 따라 장르를 선택할 때 아래 기준을 참고하세요.

| 상황 | 추천 장르 | 소요 시간 | 특징 |
|------|---------|---------|------|
| 전원 참여, 결과물 중시 | 레진아트 (코스터·키링) | 2~2.5시간 | 난이도 낮음, 완성도 높음 |
| 분위기 연출, 향 체험 | 소이캔들 만들기 | 1.5~2시간 | 후각 자극, 인테리어 선물로 활용 |
| 계절 감성 행사 | 프리저브드플라워 | 2~3시간 | 고급스러운 결과물, 장식품으로 보관 |
| 소규모 고급 체험 | 주얼리·자수 | 2.5~3시간 | 집중형 작업, 소수 정예에 적합 |
| 팀 협업 체험 | 회화·목공예 | 2.5~3시간 | 역할 분담 협업, 팀 공동 작품 제작 가능 |

어떤 장르를 선택해야 할지 모르겠다면, 출강 문의 시 인원·행사 성격·예산을 함께 알려주시면 담당자가 장르 추천을 도와드립니다.

