## 강사 수익이 안정되기까지 얼마나 걸리나요?

공예 강사 양성 플랫폼을 통해 처음 클래스를 개설하면 첫 1~3개월은 수강생 확보에 집중해야 합니다. 오센틱아트는 수강 요청 시스템을 통해 강사 프로필에 관심 있는 수강생이 사전에 수강 의사를 남길 수 있어 초기 수요 파악에 도움이 됩니다.

일반적으로 강사 프로필과 클래스 소개가 구체적일수록, 후기가 쌓일수록 수강생 전환율이 올라가는 경향이 있습니다. SNS(인스타그램 등)를 병행하면 플랫폼 외부 유입도 기대할 수 있습니다. 단, 수익 안정까지의 기간은 지역·장르·강사 활동 방식에 따라 크게 다릅니다.

