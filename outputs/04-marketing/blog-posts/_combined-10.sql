## 오센틱아트 재료 도매 채널은 어떻게 활용하나요?

오센틱아트(authenticart.kr)는 "취미를 직업으로"라는 슬로건 아래 강사·작가가 클래스 운영에 필요한 재료를 구매할 수 있는 공예 특화 쇼핑 채널을 운영합니다.

**강사 도매가 구매 — [/shop](/shop)**
오센틱아트 강사 회원은 [/shop](/shop)에서 일반 소매가보다 낮은 강사 도매가로 재료를 구매할 수 있습니다. 소매가 대비 절감폭은 품목과 수량에 따라 달라집니다. 레진아트·캔들·플라워 등 주요 공예 장르별 재료를 한 채널에서 구매할 수 있어, 여러 구매처를 돌아다닐 필요가 없습니다.

