## 단체 출강 공예 체험 비용은 얼마인가요?

비용은 인원 수, 선택 장르, 진행 시간, 재료 사양에 따라 달라집니다. 때문에 획일적인 가격을 공개하기보다 상담을 통한 맞춤 견적을 안내하고 있습니다.

견적에 영향을 주는 주요 변수는 다음과 같습니다.

- **인원 수**: 10인 이상부터 단체 출강이 가능하며, 인원이 많을수록 인당 비용이 조정될 수 있습니다.
- **장르 선택**: 레진아트·캔들 등 장르에 따라 재료비 단가가 다릅니다.
- **진행 시간**: 1.5시간 단기 체험과 3시간 심화 체험의 비용 구조가 다릅니다.
- **장소**: 회사 사무실·회의실·별도 행사장 등 장소 조건에 따라 강사 이동 비용이 포함될 수 있습니다.
- **브랜딩 커스텀 여부**: 기업 로고가 들어간 패키징이나 테마 구성 시 추가 상담이 필요합니다.

견적 상담은 [단체 출강 문의 페이지](/group-request)에서 신청하면 됩니다. 인원·희망 장르·희망 날짜를 미리 정리해두시면 상담 속도가 빨라집니다.

