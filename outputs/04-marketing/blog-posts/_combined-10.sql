## 오센틱아트 고객은 어떤 사람들인가요?

입점 여부를 결정하기 전에 고객층을 먼저 파악하는 것이 순서입니다. 오센틱아트의 주요 고객층은 세 그룹으로 나뉩니다.

**공예 강사**: 클래스를 열기 위해 재료를 반복 구매합니다. 수강생 1인당 소요되는 재료를 회차별로 준비해야 하므로 구매 주기가 짧고, 품질과 단가를 함께 고려합니다. 안정적으로 공급받을 수 있는 납품처를 찾는 경향이 강합니다.

**수강생·취미러**: 클래스를 들은 후 집에서 스스로 만들기를 원하는 수강생들이 재료를 추가로 구매합니다. 강사가 수업에서 사용한 브랜드·제품에 대한 신뢰가 높아, 강사 추천 제품에 대한 구매 전환율이 일반 쇼핑 채널보다 높을 수 있습니다.

**핸드메이드 작가**: 직접 제작한 완성 작품을 판매하고, 재료도 꾸준히 소비합니다. 특정 장르에 특화된 고품질 재료에 대한 수요가 있습니다.

세 그룹 모두 공예라는 공통 관심사를 가진 구매 의향이 높은 고객층입니다. 일반 오픈마켓에서 넓게 뿌리는 방식 대신, 이미 공예에 관심 있는 사람들에게 집중적으로 접근할 수 있다는 것이 오센틱아트 입점의 핵심 이점 중 하나입니다.

