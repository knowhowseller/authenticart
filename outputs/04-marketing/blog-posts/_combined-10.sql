## 공방 없이 강사를 시작하는 체크리스트

강사 신청 전에 준비해 두면 심사와 첫 클래스 운영에 도움이 되는 항목입니다.

- [ ] 자신 있는 장르 1~2개 선정
- [ ] 대표 작품 5~10점 사진 정리 (스마트폰 촬영도 가능)
- [ ] 원데이클래스 1회 기준 커리큘럼 초안 작성 (준비물·진행 순서·완성 작품)
- [ ] 활동 가능 지역 및 이동 범위 설정
- [ ] 운영 형태 결정 (출강·방문·대관·자택 중 택1 이상)
- [ ] 재료 도매 구매처 파악 및 회당 재료비 계산
- [ ] 수강료 설정 (재료비 + 강사비 + 이동비 포함)
- [ ] 오센틱아트 강사 프로필 소개 문구 초안 작성

