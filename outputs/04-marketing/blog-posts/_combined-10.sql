## 실제 기업 팀빌딩 공예 체험은 어떻게 진행되나요?

단체 출강 체험의 전형적인 진행 흐름을 예시로 설명합니다.

**예시: 30인 IT 기업 팀빌딩 레진아트 코스터 만들기 (2.5시간)**

- 행사 D-1주: 장소 조건 최종 확인, 재료 수량 확정
- 당일 오전: 강사 현장 도착, 테이블 세팅 및 재료 준비 (행사 시작 1시간 전)
- 행사 시작: 레진아트 기초 설명 (15분), 색상·재료 선택 및 작업 시작
- 진행 중반: 강사가 개별 참가자 작업 보조, 팀별 협업 섹션 진행
- 마무리: 경화 대기 중 완성 작품 공유, 단체 사진 촬영
- 행사 종료: 재료 정리는 강사가 담당, 작품 포장 후 귀가

담당자가 별도의 진행자 역할을 하지 않아도 강사가 전체 흐름을 이끌어가는 구조이기 때문에 준비 부담이 낮은 편입니다.

