## 회식 대신 팀빌딩 공예를 선택하는 이유가 있나요?

최근 기업 문화 행사 트렌드에서 "회식 대신 팀빌딩"이라는 흐름이 자리를 잡고 있습니다. 특히 다음과 같은 상황에서 공예 체험이 현실적인 대안으로 검토됩니다.

- 신입사원 환영 행사나 팀 합류 시즌에 자연스러운 첫 만남 자리 만들기
- 분기별 팀워크 프로그램이지만 매번 동일한 코스가 식상해진 경우
- 음주 문화에서 벗어나 전 직원이 편하게 참여할 수 있는 행사 필요 시
- 복지 포인트 활용처를 다양화하려는 경우

공예 팀빌딩은 격식 없이 진행되지만, 강사가 프로그램을 구성하고 진행하기 때문에 담당자의 준비 부담도 크지 않습니다.

