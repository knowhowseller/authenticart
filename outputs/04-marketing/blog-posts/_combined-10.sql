## 집중력과 세밀한 작업을 좋아한다면 어떤 장르가 맞나요?

### 레진아트와 자수 — 입문 특징 비교

세밀한 작업과 정교한 결과물을 좋아한다면 레진아트와 자수가 성향에 잘 맞습니다.

**레진아트**는 투명 레진 수지에 색소·조각·글리터 등을 섞어 코스터, 키링, 트레이 등 소품을 만드는 장르입니다. 배합 비율을 맞추고 기포를 제거하는 과정에서 집중력이 필요하지만, 2~3시간 안에 완성된 투명한 작품이 손에 들어옵니다. 시각적 결과물이 뚜렷하게 남기 때문에, 만들고 나서 성취감을 빠르게 느끼고 싶은 분께 맞습니다. 원데이클래스를 통해 기초 기법을 익히면 집에서 재료를 구입해 독학으로 이어갈 수 있습니다.

**자수**는 바늘과 실로 천 위에 그림을 그리는 장르입니다. 한 땀씩 쌓아가며 완성되는 구조이기 때문에 한 작품을 수 시간, 경우에 따라 수 회에 걸쳐 완성합니다. 빠른 결과보다 과정 자체를 즐기는 분, 집중하며 머리를 비우고 싶은 분께 잘 맞습니다. 도구와 재료가 간단해 초기 진입 비용이 낮고, 집에서 독학하기에도 좋은 장르입니다.

