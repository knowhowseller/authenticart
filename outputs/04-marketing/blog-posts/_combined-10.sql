## 오센틱아트 단체 출강을 선택하면 어떤 점이 다른가요?

오센틱아트는 레진·캔들·플라워·도자기·주얼리·자수·회화·목공예 전 장르에 걸쳐 인증 심사를 통과한 강사를 연결합니다. 슬로건 "취미를 직업으로"를 바탕으로 운영되는 **공예 강사 양성 플랫폼**으로, 강사의 역량과 수업 진행 방식을 플랫폼 단에서 검증한 뒤 매칭합니다.

- **전국 커버**: 서울·인천·강릉·충주·부산·제주 등 지역 강사 네트워크 운영
- **전 장르 연결**: 단일 장르 전문 서비스와 달리 행사 성격에 맞는 장르를 선택 가능
- **재료·강사 일괄 패키지**: 재료 준비와 강사 파견을 별도로 섭외할 필요 없이 한 번에 처리

기업 HR 담당자나 총무 담당자가 여러 강사와 개별 협의하는 수고 없이 원스톱으로 단체 출강을 기획할 수 있습니다.

