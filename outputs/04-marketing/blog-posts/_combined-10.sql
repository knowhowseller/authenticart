## 클래스 단가는 어떻게 정하는 게 좋을까요?

레진아트 원데이클래스 단가는 지역·장르·소요 시간에 따라 차이가 있습니다. 강사가 직접 설정하는 구조이므로, 다음 세 가지를 기준으로 잡는 분들이 많습니다.

**재료비 + 강사 시간 + 수익 마진**으로 구성하는 방식이 가장 기본적입니다. 예를 들어, 코스터 2개 기준 재료비가 1인당 약 8,000~15,000원이라면, 2시간 수업 기준 적정 단가를 역산해 볼 수 있습니다.

지역별로도 체감 단가가 다릅니다. 서울 도심권 클래스는 4~7만 원대가 많고, 지방 소도시는 3~5만 원대에서 형성되는 경우가 있습니다. 플랫폼 내 같은 장르 클래스를 참고해 초기 단가를 설정하고, 수강 이력이 쌓이면 조정하는 방식이 일반적입니다.

