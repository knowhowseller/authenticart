## 공예 재료를 저렴하게 구매하려면 어떤 기준으로 찾아야 하나요?

재료비 절감을 위한 구매처를 고를 때 단가만 보면 낭패를 겪을 수 있습니다. 강사와 작가가 실무에서 확인해야 할 기준들을 정리합니다.

**1. 단가와 최소 주문 수량(MOQ) 함께 확인**
도매 단가가 저렴해도 MOQ가 너무 높으면 초기 재고 부담이 생깁니다. 월 클래스 운영 횟수와 1회당 사용량을 계산해 실제로 소화할 수 있는 수량인지 먼저 따져보세요.

**2. 품질 인증 및 안전 기준 확인**
특히 레진류 재료는 피부 자극성, 경화 특성 등이 제품마다 다릅니다. 수강생이 직접 다루는 클래스 재료는 안전 기준이 검증된 제품을 사용하는 것이 중요합니다.

**3. 배송 속도와 재입고 주기**
클래스 일정이 정해져 있는 강사에게 배송 지연은 곧 수업 차질입니다. 정기 구매처를 정할 때는 평균 배송 기간과 재고 안정성을 함께 확인하세요.

**4. 구매처의 공예 전문성**
일반 도매 사이트보다 공예 특화 채널을 이용하면 장르별로 필요한 재료를 한 곳에서 구매할 수 있어 편리합니다. 다른 강사의 사용 후기나 추천 재료 정보도 함께 제공되는 경우 실무 참고가 됩니다.

