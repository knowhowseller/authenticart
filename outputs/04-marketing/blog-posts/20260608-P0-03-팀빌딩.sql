## 오센틱아트 단체 출강 신청 절차는 어떻게 되나요?

행사 담당자가 처음 출강 프로그램을 기획할 때 어디서부터 시작해야 할지 막막할 수 있습니다. 오센틱아트의 단체 출강 프로세스는 5단계로 진행됩니다.

**1단계: 출강 문의 접수**
[단체 출강 문의 페이지(/group-request)](/group-request)에서 인원·장르 희망·희망 일정·장소 정보를 입력하면 담당자가 1~2 영업일 내로 연락합니다.

**2단계: 요구사항 상담 및 견적 확정**
담당자와 행사 성격, 장르, 시간, 예산을 협의하고 맞춤 견적을 확정합니다. 이 단계에서 장르 변경이나 프로그램 조정이 가능합니다.

**3단계: 강사 매칭 및 일정 확정**
행사 지역과 장르에 맞는 오센틱아트 인증 강사를 매칭합니다. 서울·인천·강릉·충주·부산·제주 등 전국 지역 커버가 가능합니다.

**4단계: 재료 준비 및 사전 확인**
강사가 필요한 재료와 도구를 직접 준비해 현장에 가져옵니다. 장소 조건(테이블 면적, 환기, 콘센트 여부)은 사전에 체크리스트로 확인합니다.

**5단계: 현장 진행 및 작품 완성**
강사가 진행을 맡아 참가자 전원이 작품을 완성하도록 안내합니다. 프로그램 종료 후 정산이 이루어집니다.

