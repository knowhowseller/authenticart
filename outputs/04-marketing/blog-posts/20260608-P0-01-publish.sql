## 수수료 말고 플랫폼 선택 시 고려해야 할 요소는 무엇인가요?

수수료는 중요하지만 전부는 아닙니다. 플랫폼 선택 시 함께 확인해야 할 항목들입니다.

**정산 주기**: 수업 완료 후 얼마나 빠르게 정산되는지 확인하세요. 오센틱아트는 수강생 결제 완료 기준으로 정산이 진행됩니다.

**수강생 트래픽**: 플랫폼이 자체적으로 수강생을 유입해 주는지, 강사가 직접 마케팅해야 하는지 구조가 다릅니다. 오센틱아트는 수강생의 클래스 오픈 요청 시스템을 통해 수요를 사전에 확인할 수 있습니다.

**클래스 개설 자유도**: 가격·정원·일정을 강사가 자유롭게 설정할 수 있는지, 플랫폼이 개입하는 범위가 어느 정도인지 파악해야 합니다.

**강사 프로필 노출**: 플랫폼 내 검색 노출 방식과 강사 프로필 구성 자유도도 신규 강사에게는 중요한 요소입니다.

**초기 비용**: 클래스 등록이나 입점 시 별도 비용이 발생하는지 확인하세요. 오센틱아트는 수강생 결제 시에만 수수료가 발생하며, 클래스 등록 자체에는 별도 고정 비용이 없습니다.

