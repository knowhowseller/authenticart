## 가죽공예와 주얼리가 뜨는 이유는 무엇인가요?

### 가죽공예 — 실용성과 나만의 소품

가죽공예는 카드지갑, 파우치, 키링 등 실생활에서 매일 쓰는 소품을 직접 만들 수 있다는 점에서 관심이 늘고 있습니다. 재료 자체의 내구성과 완성도가 높아, 만들고 나서 오래 쓸 수 있는 결과물을 원하는 분들에게 맞습니다. 원데이클래스 기준으로는 카드지갑이나 코인 파우치 정도가 2~3시간 내 완성 가능한 구성입니다.

### 실버주얼리 — 착용 가능한 고급 취미

실버주얼리는 은을 가공해 반지, 귀걸이, 팔찌 등을 직접 만드는 장르입니다. 완성 후 실제로 착용할 수 있다는 점, 그리고 귀금속을 다룬다는 특별함이 "고급 취미" 이미지를 만들어 줍니다. 원데이클래스 참여 비용이 다른 장르보다 높은 편이지만, 완성품의 가치감이 높아 선물 목적으로 참여하는 수요도 있습니다.

