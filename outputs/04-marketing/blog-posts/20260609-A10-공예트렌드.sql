## 2026년 공예 취미 시장, 어떤 흐름이 보이나요?

공예 취미가 "특별한 취미"에서 "일상의 선택지"로 이동하고 있습니다. 헬스장 대신 공방을 찾거나, 주말 저녁 원데이클래스를 카페 모임처럼 예약하는 패턴이 낯설지 않아진 것이 2025~2026년의 변화입니다.

이 흐름을 만드는 배경에는 몇 가지 공통 요소가 있습니다. 화면에서 멀어지고 손을 쓰고 싶다는 수요, 완성품이라는 구체적인 결과물, 혼자 혹은 소규모로 즐길 수 있는 구조, 그리고 취미가 수익으로 연결될 수 있다는 가능성입니다.

