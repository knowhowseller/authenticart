## 도자기는 왜 다시 주목받고 있나요?

도자기는 디지털 피로가 쌓인 시기에 재주목받는 대표 장르입니다. 흙을 손으로 직접 빚는 물리적 감각이 화면 없이 집중할 수 있는 환경을 만들어 주기 때문입니다. 원데이클래스에서는 물레 체험이나 핀칭 방식으로 컵이나 그릇 형태를 만드는 입문 구성이 많습니다.

도자기의 특성상 건조·소성 과정이 있어 완성품을 그날 가져가기 어렵습니다. 대신 이 과정이 "기다리는 재미"로 작용하면서 원데이 체험 이후 정기 수업으로 전환하는 수요가 높은 편입니다. 취미를 깊이 파고드는 고관여 장르를 찾는 분들에게 맞습니다.

