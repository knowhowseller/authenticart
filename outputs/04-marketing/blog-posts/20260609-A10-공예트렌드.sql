## 레진아트는 왜 계속 인기 장르로 남아있나요?

레진아트는 짧은 시간 안에 시각적으로 완성도 높은 작품을 만들 수 있다는 점에서 원데이클래스 입문 장르로 가장 자주 선택됩니다. 코스터, 키링, 트레이 등 실생활 소품으로 바로 활용 가능하고, 투명 레진 안에 색소와 조각을 넣어 매번 다른 결과물이 나오는 구조가 반복 참여를 유도합니다.

2026년에는 기존 에폭시 레진에서 UV 레진 활용 영역이 확장되고, 누빔·마블 기법 등 응용 기법에 대한 수요도 함께 늘고 있습니다. 입문 후 심화 클래스로 이어지는 패턴이 뚜렷한 장르 중 하나입니다.

