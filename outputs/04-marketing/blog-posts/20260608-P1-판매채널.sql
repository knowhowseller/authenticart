## 공예 작품 판매 채널을 선택할 때 어떤 기준으로 비교해야 하나요?

채널 선택 시 확인할 세 가지 기준입니다.

**1. 타겟 구매자 적합도**
내 작품을 살 가능성이 높은 사람들이 실제로 모여 있는 채널인지 확인하세요. 공예 재료나 공예 작품이라면, 공예에 관심 있는 고객이 모인 공간이 일반 쇼핑 플랫폼보다 전환율이 높을 수 있습니다.

**2. 수수료 구조와 운영 비용**
판매 수수료 외에 등록비, 월 이용료 등 고정 비용이 있는지 확인하세요. 채널마다 구조가 다르므로 각 플랫폼의 공식 정책에서 실제 조건을 확인하는 것이 필요합니다.

**3. 운영 관리 부담**
사진 등록, 재고 관리, 주문·배송 처리, 문의 대응 등 운영 부담이 각 채널마다 다릅니다. 혼자 운영하는 작가라면 관리가 간단한 채널을 우선 고려하는 것이 현실적입니다.

