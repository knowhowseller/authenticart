## 어떤 작가에게 오센틱아트 마켓이 맞고, 어떤 작가에게 다른 채널이 맞나요?

오센틱아트 마켓은 다음과 같은 경우에 맞습니다.

- 공예 장르(레진아트, 소이캔들, 자수, 프리저브드플라워 등) 작품을 판매하는 작가
- 공예에 관심 있는 구매자, 즉 클래스 수강생·강사를 주 타겟으로 삼는 경우
- 클래스 강사이면서 자신의 작품과 재료를 함께 판매하고 싶은 경우
- 재료 공급사로서 공예 강사·수강생에게 직접 노출되길 원하는 경우

다른 채널이 더 맞는 경우도 있습니다.

- 공예와 무관한 일반 소비재를 판매하는 경우 → 오픈마켓이 유리
- 광범위한 일반 소비자 대상 핸드메이드 작품 노출이 목표인 경우 → 핸드메이드 전문몰 우선 검토
- 브랜드 팔로워를 직접 쌓아 나가려는 경우 → SNS 채널 병행

채널은 배타적으로 선택할 필요가 없습니다. 여러 채널에 동시 입점해 각 채널의 강점을 활용하는 방식이 일반적입니다.

