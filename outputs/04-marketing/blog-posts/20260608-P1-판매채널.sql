## 핸드메이드 작품, 왜 채널 선택이 판매 결과를 좌우하나요?

직접 만든 레진 코스터, 소이캔들, 자수 소품 — 완성도를 높여도 '어디서 파느냐'에 따라 팔리기도 하고, 아무도 보지 않기도 합니다. 공예 작품을 구매하려는 사람이 실제로 찾아오는 곳에 작품을 올려야 판매가 일어납니다.

