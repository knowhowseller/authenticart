## 오센틱아트 마켓에 작품이나 재료를 등록하는 절차는 어떻게 되나요?

**작품 등록 (핸드메이드 작가)**

1. 오센틱아트(www.authenticart.co.kr) 로그인
2. [/my/artworks](/my/artworks) 접속 → 작품 제목, 설명, 가격, 대표 이미지 등록
3. 검토 후 [작품 마켓](/artworks)에 게시

작품 마켓에는 공예 클래스를 탐색하는 수강생과 강사가 유입되어, 공예 작품 구매 의향이 있는 고객에게 노출됩니다.

**재료 벤더 입점 (재료 공급사·도매업체)**

1. [/my/vendor/apply](/my/vendor/apply) 접속 → 사업자 정보, 취급 재료 카테고리 입력
2. 입점 심사 후 [스토어 페이지](/shop/stores) 개설
3. 강사·수강생 대상 재료 판매 시작

두 경로 모두 공예에 관심 있는 고객이 이미 플랫폼에 머무는 상태에서 상품이 노출된다는 점에서, 공예 작품·재료 판매에 특화된 구조입니다.

